import 'dart:io';
import 'dart:typed_data';

import 'package:path/path.dart' as p;
import 'package:wardrobe_domain/wardrobe_domain.dart';

/// App-private file storage addressed by *relative* paths.
///
/// The database stores only relative paths (REQUIREMENTS §11), so files stay
/// valid after reinstall/restore when the platform moves the app container.
/// Relative paths always use `/` separators regardless of platform.
abstract interface class FileStore {
  /// Atomically writes [bytes] to [relativePath] (temp file, then rename).
  Future<Result<void>> writeBytes(String relativePath, Uint8List bytes);

  /// Atomically copies [source] into the store at [relativePath].
  Future<Result<void>> copyIn(File source, String relativePath);

  Future<Result<Uint8List>> readBytes(String relativePath);

  Future<bool> exists(String relativePath);

  /// Deletes the file. Deleting a missing file succeeds.
  Future<Result<void>> delete(String relativePath);

  /// Relative paths of all files under [relativeDir] (recursive), for
  /// orphan clean-up. Returns an empty list when the folder does not exist.
  Future<Result<List<String>>> list(String relativeDir);

  /// Absolute file for platform APIs that need a real path (e.g. image
  /// decoding). Never persist the result.
  File resolve(String relativePath);
}

/// Thrown for a malformed relative path. This is a programming error (paths
/// are generated by the app), so it is an [ArgumentError], not a failure.
final class InvalidStorePathError extends ArgumentError {
  InvalidStorePathError(String path, String reason)
    : super.value(path, 'relativePath', reason);
}

/// [FileStore] rooted at a private directory on the local file system.
final class LocalFileStore implements FileStore {
  LocalFileStore(this.root);

  /// Absolute root, typically `<applicationSupport>/files`.
  final Directory root;

  static const _tempSuffix = '.tmp';

  /// POSIX ENOSPC (Android, iOS) and Windows ERROR_DISK_FULL /
  /// ERROR_HANDLE_DISK_FULL.
  static const _noSpaceCodes = {28, 112, 39};

  @override
  File resolve(String relativePath) {
    final segments = _validate(relativePath);
    return File(p.joinAll([root.path, ...segments]));
  }

  @override
  Future<Result<void>> writeBytes(String relativePath, Uint8List bytes) =>
      _atomically(
        relativePath,
        (temp) => temp.writeAsBytes(bytes, flush: true),
      );

  @override
  Future<Result<void>> copyIn(File source, String relativePath) =>
      _atomically(relativePath, (temp) => source.copy(temp.path));

  @override
  Future<Result<Uint8List>> readBytes(String relativePath) async {
    final file = resolve(relativePath);
    try {
      return Success(await file.readAsBytes());
    } on PathNotFoundException catch (e) {
      return Failure(NotFoundFailure('No stored file at $relativePath: $e'));
    } on FileSystemException catch (e) {
      return Failure(_mapError('Could not read $relativePath', e));
    }
  }

  @override
  Future<bool> exists(String relativePath) => resolve(relativePath).exists();

  @override
  Future<Result<void>> delete(String relativePath) async {
    final file = resolve(relativePath);
    try {
      if (await file.exists()) await file.delete();
      return const Success(null);
    } on FileSystemException catch (e) {
      return Failure(_mapError('Could not delete $relativePath', e));
    }
  }

  @override
  Future<Result<List<String>>> list(String relativeDir) async {
    final segments = _validate(relativeDir);
    final dir = Directory(p.joinAll([root.path, ...segments]));
    try {
      if (!await dir.exists()) return const Success([]);
      final files = <String>[];
      await for (final entity in dir.list(
        recursive: true,
        followLinks: false,
      )) {
        if (entity is File && !entity.path.endsWith(_tempSuffix)) {
          final rel = p.relative(entity.path, from: root.path);
          files.add(p.split(rel).join('/'));
        }
      }
      files.sort();
      return Success(files);
    } on FileSystemException catch (e) {
      return Failure(_mapError('Could not list $relativeDir', e));
    }
  }

  Future<Result<void>> _atomically(
    String relativePath,
    Future<Object?> Function(File temp) write,
  ) async {
    final target = resolve(relativePath);
    final temp = File('${target.path}$_tempSuffix');
    try {
      await target.parent.create(recursive: true);
      await write(temp);
      await temp.rename(target.path);
      return const Success(null);
    } on FileSystemException catch (e) {
      await _deleteQuietly(temp);
      return Failure(_mapError('Could not write $relativePath', e));
    }
  }

  /// Best-effort clean-up of a partially written temp file. A failure here is
  /// reported through the original error, so it is safe to ignore.
  Future<void> _deleteQuietly(File file) async {
    try {
      if (await file.exists()) await file.delete();
    } on FileSystemException {
      // The temp file is skipped by list() and overwritten on the next write.
    }
  }

  AppFailure _mapError(String message, FileSystemException e) {
    final code = e.osError?.errorCode;
    if (code != null && _noSpaceCodes.contains(code)) {
      return InsufficientStorageFailure(message, cause: e);
    }
    return StorageFailure(message, cause: e);
  }

  static List<String> _validate(String relativePath) {
    if (relativePath.isEmpty) {
      throw InvalidStorePathError(relativePath, 'must not be empty');
    }
    if (relativePath.contains(r'\')) {
      throw InvalidStorePathError(relativePath, 'must use / separators');
    }
    if (relativePath.startsWith('/') || p.windows.isAbsolute(relativePath)) {
      throw InvalidStorePathError(relativePath, 'must be relative');
    }
    final segments = relativePath.split('/');
    for (final s in segments) {
      if (s.isEmpty || s == '.' || s == '..') {
        throw InvalidStorePathError(relativePath, 'invalid segment "$s"');
      }
    }
    return segments;
  }
}
